/**
 * The bridge CLI (tc.mjs) every wired agent runs from its own shell to reach
 * what is wired to it on the canvas: other agents (Claude ↔ Gemini ↔ Codex
 * over pipelines, or an orchestrator's workers), AI models and data sources.
 *
 * It only talks to `/bridge/<own terminal id>/*` on the local TermCanvas
 * API, so an agent can reach exactly what is wired to it and nothing else.
 * Plain Node, no dependencies, so it runs from any agent's shell.
 */

export type BridgeRole = "orchestrator" | "agent";

export function buildBridgeScript(options: {
  terminalId: string;
  portFile: string;
  role: BridgeRole;
}): string {
  const header =
    "#!/usr/bin/env node\n" +
    "// TermCanvas bridge. Generated by TermCanvas; edits are overwritten.\n" +
    `const SELF_ID = ${JSON.stringify(options.terminalId)};\n` +
    `const PORT_FILE = ${JSON.stringify(options.portFile)};\n` +
    `const ROLE = ${JSON.stringify(options.role)};\n`;
  return header + BRIDGE_SCRIPT_BODY;
}

// Written without template literals so it can live inside String.raw.
const BRIDGE_SCRIPT_BODY = String.raw`
import fs from "node:fs";
import path from "node:path";
import http from "node:http";
import { fileURLToPath } from "node:url";

const BASE = "/bridge/" + encodeURIComponent(SELF_ID);
const DONE_STATES = new Set(["turn_complete", "turn_aborted"]);
const ACTIVE_STATES = new Set(["thinking", "in_turn", "tool_running", "tool_pending"]);
const STATE_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), ".state");
const START_GRACE_MS = 30000;
const MAX_PRINT_CHARS = 20000;
// Agents without turn telemetry (e.g. Gemini CLI): a turn is over when the
// agent printed something after our message and then went quiet this long.
const QUIET_MS = 6000;
const MIN_TURN_MS = 4000;

function readPort() {
  let raw;
  try {
    raw = fs.readFileSync(PORT_FILE, "utf-8");
  } catch {
    throw new Error("TermCanvas is not running (no port file at " + PORT_FILE + ")");
  }
  const port = parseInt(raw.split("\n")[0].trim(), 10);
  if (!port) throw new Error("TermCanvas port file is empty: " + PORT_FILE);
  return port;
}

function api(method, urlPath, body, timeoutMs) {
  return new Promise((resolve, reject) => {
    const data = body === undefined ? undefined : JSON.stringify(body);
    const headers = data
      ? { "Content-Type": "application/json", "Content-Length": Buffer.byteLength(data) }
      : {};
    const req = http.request(
      {
        hostname: "127.0.0.1",
        port: readPort(),
        path: urlPath,
        method,
        headers,
        timeout: timeoutMs || 30000,
      },
      (res) => {
        let text = "";
        res.setEncoding("utf8");
        res.on("data", (chunk) => (text += chunk));
        res.on("end", () => {
          let json;
          try {
            json = text ? JSON.parse(text) : {};
          } catch {
            json = { error: text };
          }
          if (res.statusCode >= 400) {
            const error = new Error(json.error || "HTTP " + res.statusCode);
            error.status = res.statusCode;
            reject(error);
          } else resolve(json);
        });
      },
    );
    req.on("timeout", () => req.destroy(new Error("TermCanvas API timed out")));
    req.on("error", reject);
    if (data) req.write(data);
    req.end();
  });
}

function parseArgs(argv) {
  const positional = [];
  const flags = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg.startsWith("--")) {
      const key = arg.slice(2);
      const next = argv[i + 1];
      if (next !== undefined && !next.startsWith("--")) {
        flags[key] = next;
        i++;
      } else {
        flags[key] = true;
      }
    } else {
      positional.push(arg);
    }
  }
  return { positional, flags };
}

function truncate(text, max) {
  if (text.length <= max) return text;
  return text.slice(0, max) + "\n... [truncated " + (text.length - max) + " chars]";
}

function readTextArg(rest, flags) {
  if (typeof flags.file === "string") return fs.readFileSync(flags.file, "utf-8");
  const text = rest.join(" ");
  if (!text.trim()) throw new Error("No text given. Pass the text or --file <path>.");
  return text;
}

function sentMarkerPath(agentId) {
  return path.join(STATE_DIR, agentId.replace(/[^A-Za-z0-9_-]/g, "_") + ".json");
}

function recordSent(agentId) {
  fs.mkdirSync(STATE_DIR, { recursive: true });
  fs.writeFileSync(sentMarkerPath(agentId), JSON.stringify({ sentAt: Date.now() }));
}

function readSentAt(agentId) {
  try {
    return JSON.parse(fs.readFileSync(sentMarkerPath(agentId), "utf-8")).sentAt || 0;
  } catch {
    return 0;
  }
}

/** Tell TermCanvas what happened, for the feed. Never fails the command. */
async function reportEvent(event) {
  try {
    await api("POST", BASE + "/event", event, 5000);
  } catch {
    // The feed is best effort.
  }
}

function describeModel(m) {
  return m.connectorName + " · " + (m.model || "default model") + " · " + m.transport;
}

async function cmdStatus() {
  const m = await api("GET", BASE);
  const lines = [];
  lines.push("You: " + m.self.title + " [" + m.self.type + "]" + (m.self.role === "orchestrator" ? " - ORCHESTRATOR" : ""));
  lines.push("");
  lines.push("Agents wired to you (" + m.agents.length + "):");
  if (m.agents.length === 0) {
    lines.push("  (none - the user wires agents to you on the canvas)");
  }
  m.agents.forEach((a, i) => {
    lines.push(
      "  " + (i + 1) + ". " + a.name + "  [" + a.type + "]  state=" + (a.turnState || a.status) +
        (a.ptyId ? "" : "  (not running)") + "  via=" + a.via + "  id=" + a.id,
    );
  });
  lines.push("");
  lines.push("AI models wired to you (" + m.models.length + "):");
  if (m.models.length === 0) lines.push("  (none)");
  m.models.forEach((model, i) => {
    lines.push("  M" + (i + 1) + ". " + model.name + "  [" + describeModel(model) + "]");
    if (model.persona) {
      for (const line of model.persona.split("\n")) lines.push("      " + line);
    }
  });
  lines.push("");
  lines.push("Sources wired to you (" + m.sources.length + "):");
  if (m.sources.length === 0) lines.push("  (none)");
  m.sources.forEach((s, i) => {
    lines.push("  S" + (i + 1) + ". " + s.name + "  [" + s.kind + "]" + (s.url ? "  " + s.url : ""));
    if (s.description) {
      for (const line of s.description.split("\n")) lines.push("      " + line);
    }
  });
  console.log(lines.join("\n"));
}

async function sendTo(agentRef, text, options) {
  const result = await api("POST", BASE + "/send", { agent: agentRef, text });
  recordSent(result.agent.id);
  if (!options || !options.quiet) {
    console.log("Sent to " + result.agent.name + " (" + result.agent.id + ").");
  }
  return result.agent;
}

async function cmdSend(rest, flags) {
  const agent = rest.shift();
  if (!agent) throw new Error("Usage: send <agent> <text> | --file <path>");
  return sendTo(agent, readTextArg(rest, flags));
}

/**
 * Poll until the agent's turn is over. Returns { code, name, state, reply }:
 * code 0 = reply ready, 2 = still working, 3 = waiting for the user.
 */
async function waitFor(agentRef, timeoutSec) {
  const deadline = Date.now() + (timeoutSec || 100) * 1000;
  let agentId = null;
  let sentAt = 0;
  while (true) {
    const info = await api("GET", BASE + "/agent?waiting=1&agent=" + encodeURIComponent(agentId || agentRef));
    const a = info.agent;
    if (!agentId) {
      agentId = a.id;
      sentAt = readSentAt(agentId);
    }
    const state = a.turnState || "unknown";
    let done = false;
    if (state !== "unknown") {
      const startedAt = a.turnStartedAt ? Date.parse(a.turnStartedAt) : 0;
      const started =
        !sentAt ||
        startedAt >= sentAt - 2000 ||
        ACTIVE_STATES.has(state) ||
        Date.now() - sentAt > START_GRACE_MS;
      done = started && DONE_STATES.has(state);
    } else {
      const lastOutput = a.lastOutputAt ? Date.parse(a.lastOutputAt) : 0;
      const answered = !sentAt || lastOutput > sentAt + 1000;
      done =
        answered &&
        lastOutput > 0 &&
        Date.now() - lastOutput >= QUIET_MS &&
        Date.now() - sentAt >= MIN_TURN_MS;
    }
    if (done && !a.awaitingApproval) {
      const r = await api("GET", BASE + "/reply?agent=" + encodeURIComponent(agentId));
      return { code: 0, id: a.id, name: a.name, state, reply: r.reply || "" };
    }
    if (state === "awaiting_input" || a.awaitingApproval) {
      return { code: 3, id: a.id, name: a.name, state };
    }
    if (!a.ptyId) {
      throw new Error(a.name + " is not running. Ask the user to open or restart that terminal.");
    }
    if (Date.now() >= deadline) return { code: 2, id: a.id, name: a.name, state };
    await new Promise((resolve) => setTimeout(resolve, 2500));
  }
}

function printWaitResult(result, agentRef) {
  if (result.code === 0) {
    console.log("[" + result.name + " finished" + (result.state === "unknown" ? "" : ": " + result.state) + "]");
    console.log(truncate(result.reply || "(no reply text found)", MAX_PRINT_CHARS));
  } else if (result.code === 3) {
    console.log(
      "WAITING_FOR_APPROVAL: " + result.name + " is waiting for the user to approve or answer something in its terminal.",
    );
  } else {
    console.log(
      "STILL_WORKING: " + result.name + " state=" + result.state + ". Run wait again" +
        (result.state === "unknown" ? " (or reply " + agentRef + " to read its screen so far)." : "."),
    );
  }
  if (result.code !== 0) process.exitCode = result.code;
  return result.code;
}

async function cmdWait(rest, flags) {
  const agentRef = rest.shift();
  if (!agentRef) throw new Error("Usage: wait <agent> [--timeout 100]");
  return printWaitResult(await waitFor(agentRef, parseInt(flags.timeout, 10) || 100), agentRef);
}

// ---- AI models -------------------------------------------------------------

function matchModels(models, ref) {
  const numbered = /^M(\d+)$/i.exec(ref);
  if (numbered) {
    const model = models[parseInt(numbered[1], 10) - 1];
    return model ? [model] : [];
  }
  const lower = ref.toLowerCase();
  const exact = models.filter((m) => m.id === ref || m.name.toLowerCase() === lower);
  if (exact.length > 0) return exact;
  return models.filter(
    (m) =>
      m.connector === lower ||
      m.connectorName.toLowerCase() === lower ||
      m.name.toLowerCase().includes(lower),
  );
}

function matchAgents(agents, ref) {
  if (/^\d+$/.test(ref)) {
    const agent = agents[parseInt(ref, 10) - 1];
    return agent ? [agent] : [];
  }
  const lower = ref.toLowerCase();
  const exact = agents.filter((a) => a.id === ref || a.name.toLowerCase() === lower);
  if (exact.length > 0) return exact;
  return agents.filter((a) => a.type === lower || a.name.toLowerCase().includes(lower));
}

/** Decide whether a reference names a wired agent or a wired model. */
function classifyPeer(manifest, ref) {
  const models = matchModels(manifest.models, ref);
  const agents = /^M\d+$/i.test(ref) ? [] : matchAgents(manifest.agents, ref);
  if (agents.length === 1 && models.length === 0) return { kind: "agent", item: agents[0] };
  if (models.length === 1 && agents.length === 0) return { kind: "model", item: models[0] };
  if (agents.length === 0 && models.length === 0) {
    throw new Error(
      "Nothing wired to you matches '" + ref + "'. Run peers to see agents (1, 2…) and models (M1…).",
    );
  }
  throw new Error(
    "'" + ref + "' is ambiguous. Use an agent number (1, 2…) or a model number (M1…) from peers.",
  );
}

async function askModel(model, prompt, flags, label) {
  const timeoutSec = parseInt(flags.timeout, 10) || 180;
  return api(
    "POST",
    BASE + "/model",
    { model: model.id, prompt, timeoutSec, label },
    (timeoutSec + 30) * 1000,
  );
}

function modelHeader(r) {
  const usage = r.usage && r.usage.outputTokens ? ", " + r.usage.outputTokens + " tokens" : "";
  return (
    "[" + r.model.name + " · " + r.model.model + " · " + r.model.transport + " · " +
    (r.latencyMs / 1000).toFixed(1) + "s" + usage + "]"
  );
}

async function cmdAsk(rest, flags) {
  const ref = rest.shift();
  if (!ref) throw new Error("Usage: ask <agent|model> <text> | --file <path>");
  const text = readTextArg(rest, flags);
  const manifest = await api("GET", BASE);
  const peer = classifyPeer(manifest, ref);
  if (peer.kind === "model") {
    const r = await askModel(peer.item, text, flags);
    console.log(modelHeader(r));
    console.log(truncate(r.text, MAX_PRINT_CHARS));
    return 0;
  }
  const agent = await sendTo(peer.item.id, text);
  return printWaitResult(await waitFor(agent.id, parseInt(flags.timeout, 10) || 100), ref);
}

async function cmdConsult(rest, flags) {
  const ref = rest.shift();
  if (!ref) throw new Error("Usage: consult <model> <text> | --file <path>");
  const text = readTextArg(rest, flags);
  const manifest = await api("GET", BASE);
  const models = matchModels(manifest.models, ref);
  if (models.length !== 1) {
    throw new Error(
      "No single wired model matches '" + ref + "'. Wired models: " +
        (manifest.models.map((m, i) => "M" + (i + 1) + " " + m.name).join(", ") || "none"),
    );
  }
  const r = await askModel(models[0], text, flags);
  console.log(modelHeader(r));
  console.log(truncate(r.text, MAX_PRINT_CHARS));
}

function pickList(all, spec, match) {
  if (typeof spec !== "string") return all;
  const picked = [];
  for (const ref of spec.split(",").map((part) => part.trim()).filter(Boolean)) {
    const found = match(all, ref);
    if (found.length !== 1) throw new Error("'" + ref + "' does not name exactly one wired peer.");
    if (!picked.includes(found[0])) picked.push(found[0]);
  }
  return picked;
}

/** Ask every wired model (and with --agents, every agent) the same question. */
async function cmdCouncil(rest, flags) {
  const question = readTextArg(rest, flags);
  const manifest = await api("GET", BASE);
  const models = flags.models === true ? manifest.models : pickList(manifest.models, flags.models, matchModels);
  const agents =
    flags.agents === undefined
      ? []
      : flags.agents === true
        ? manifest.agents
        : pickList(manifest.agents, flags.agents, matchAgents);
  if (models.length + agents.length === 0) {
    throw new Error("No models (or agents with --agents) are wired to you. Run peers.");
  }
  console.log(
    "Council of " + [...models.map((m) => m.name), ...agents.map((a) => a.name)].join(", ") + "…",
  );
  const sent = [];
  for (const agent of agents) sent.push(await sendTo(agent.id, question, { quiet: true }));
  const modelRuns = models.map((model) =>
    askModel(model, question, flags, "council").then(
      (r) => modelHeader(r) + "\n" + truncate(r.text, MAX_PRINT_CHARS),
      (error) => "[" + model.name + " failed] " + error.message,
    ),
  );
  const agentRuns = sent.map((agent) =>
    waitFor(agent.id, parseInt(flags.timeout, 10) || 180).then(
      (result) =>
        result.code === 0
          ? "[" + result.name + "]\n" + truncate(result.reply || "(no reply text found)", MAX_PRINT_CHARS)
          : "[" + result.name + "] " + (result.code === 3 ? "waits for the user's approval" : "still working - use wait " + result.id),
      (error) => "[" + agent.name + " failed] " + error.message,
    ),
  );
  const answers = await Promise.all([...modelRuns, ...agentRuns]);
  console.log("");
  console.log(answers.join("\n\n----------------------------------------\n\n"));
}

async function cmdBroadcast(rest, flags) {
  const text = readTextArg(rest, flags);
  const manifest = await api("GET", BASE);
  if (manifest.agents.length === 0) throw new Error("No agents are wired to you.");
  for (const agent of manifest.agents) {
    try {
      await sendTo(agent.id, text);
    } catch (error) {
      console.log("Could not send to " + agent.name + ": " + error.message);
    }
  }
  console.log("Now run wait <agent> for each reply you need.");
}

async function cmdReply(rest) {
  const agentRef = rest.shift();
  if (!agentRef) throw new Error("Usage: reply <agent>");
  const r = await api("GET", BASE + "/reply?agent=" + encodeURIComponent(agentRef));
  console.log("[" + r.agent.name + " state=" + (r.agent.turnState || "unknown") + "]");
  console.log(truncate(r.reply || "(no reply text found)", MAX_PRINT_CHARS));
}

function resolveSource(manifest, ref) {
  const sources = manifest.sources;
  const m = /^S?(\d+)$/i.exec(ref);
  if (m) {
    const s = sources[parseInt(m[1], 10) - 1];
    if (s) return s;
  }
  const lower = ref.toLowerCase();
  const exact = sources.filter((s) => s.id === ref || s.name.toLowerCase() === lower);
  if (exact.length === 1) return exact[0];
  const partial = sources.filter((s) => s.name.toLowerCase().includes(lower));
  if (partial.length === 1) return partial[0];
  throw new Error(
    "No single wired source matches '" + ref + "'. Wired: " +
      (sources.map((s, i) => "S" + (i + 1) + " " + s.name).join(", ") || "none"),
  );
}

function sheetCsvUrl(url) {
  const m = /\/spreadsheets\/d\/([A-Za-z0-9_-]+)/.exec(url);
  if (!m) return url;
  const gid = /[#?&]gid=(\d+)/.exec(url);
  return "https://docs.google.com/spreadsheets/d/" + m[1] + "/export?format=csv" + (gid ? "&gid=" + gid[1] : "");
}

function limitLines(text, maxLines) {
  const lines = text.split(/\r?\n/);
  if (lines.length <= maxLines) return text;
  return lines.slice(0, maxLines).join("\n") + "\n... [" + (lines.length - maxLines) + " more lines, use --lines]";
}

async function cmdSource(rest, flags) {
  const ref = rest.shift();
  if (!ref) throw new Error("Usage: source <S#|name> [--lines 200] [--query \"k=v&k2=v2\"]");
  const manifest = await api("GET", BASE);
  const s = resolveSource(manifest, ref);
  const maxLines = parseInt(flags.lines, 10) || 200;
  console.log("[" + s.name + " - " + s.kind + "]");
  if (s.description && s.kind !== "note") console.log("Notes: " + s.description);
  if (s.kind === "note") {
    console.log(s.description || "(empty note)");
    await reportEvent({ kind: "read", source: s.id, text: "(note)" });
    return;
  }
  if (!s.url) throw new Error("Source '" + s.name + "' has no URL/path set on the canvas.");
  if (s.kind === "file") {
    const stat = fs.statSync(s.url);
    if (stat.isDirectory()) {
      console.log(fs.readdirSync(s.url).join("\n"));
    } else {
      console.log(truncate(limitLines(fs.readFileSync(s.url, "utf-8"), maxLines), MAX_PRINT_CHARS));
    }
    await reportEvent({ kind: "read", source: s.id, text: s.url });
    return;
  }
  let target = s.kind === "sheet" ? sheetCsvUrl(s.url) : s.url;
  if (typeof flags.query === "string" && flags.query && s.kind !== "sheet") {
    target += (target.includes("?") ? "&" : "?") + flags.query.replace(/^\?/, "");
  }
  const res = await fetch(target, { redirect: "follow" });
  const body = await res.text();
  const type = res.headers.get("content-type") || "";
  if (s.kind === "sheet" && (type.includes("text/html") || !res.ok)) {
    throw new Error(
      "Could not read the sheet as CSV (HTTP " + res.status + "). Share it as 'Anyone with the link: Viewer', " +
        "or wire an n8n webhook source that reads it.",
    );
  }
  if (s.kind === "n8n" && res.status === 404 && body.includes("not registered")) {
    throw new Error(
      "This n8n webhook does not accept GET (or its workflow is not published). " +
        "If it is an action webhook, use: trigger " + ref + " --data '<json>'",
    );
  }
  if (!res.ok) console.log("HTTP " + res.status);
  console.log(truncate(limitLines(body, maxLines), MAX_PRINT_CHARS));
  await reportEvent({
    kind: "read",
    source: s.id,
    text: "GET " + target.replace(/[?#].*$/, "") + (flags.query ? "?" + flags.query : ""),
    status: res.status,
  });
}

async function cmdTrigger(rest, flags) {
  const ref = rest.shift();
  if (!ref) throw new Error("Usage: trigger <S#|name> [--data '<json>' | --file payload.json]");
  const manifest = await api("GET", BASE);
  const s = resolveSource(manifest, ref);
  if (!s.url) throw new Error("Source '" + s.name + "' has no URL set on the canvas.");
  if (s.kind === "file" || s.kind === "note") throw new Error("Source '" + s.name + "' cannot be triggered.");
  let payload = {};
  if (typeof flags.file === "string") payload = JSON.parse(fs.readFileSync(flags.file, "utf-8"));
  else if (typeof flags.data === "string") payload = JSON.parse(flags.data);
  const res = await fetch(s.url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  });
  const body = await res.text();
  console.log("[" + s.name + "] HTTP " + res.status);
  console.log(truncate(body, MAX_PRINT_CHARS));
  await reportEvent({
    kind: "trigger",
    source: s.id,
    text: JSON.stringify(payload).slice(0, 2000),
    status: res.status,
  });
  if (!res.ok) process.exitCode = 1;
}

const HELP = [
  "TermCanvas bridge (" + ROLE + ")",
  "  status | peers                          what is wired to you",
  "  ask <agent|model> <text> | --file <p>   message an agent and wait, or ask a model",
  "  send <agent> <text> | --file <path>     message an agent without waiting",
  "  wait <agent> [--timeout 100]            wait for its reply",
  "  reply <agent>                           print its latest reply again",
  "  consult <model> <text> | --file <path>  ask a wired AI model",
  "  council <question> [--models M1,M2] [--agents [1,2]]   ask several at once, compare",
  "  broadcast <text> | --file <path>        message every wired agent",
  "  source <S#|name> [--lines 200] [--query \"k=v\"]",
  "  trigger <S#|name> [--data '<json>' | --file payload.json]",
].join("\n");

async function main() {
  const [command, ...argv] = process.argv.slice(2);
  const { positional, flags } = parseArgs(argv);
  switch (command) {
    case "status":
    case "peers":
      return cmdStatus();
    case "send":
      return cmdSend(positional, flags);
    case "wait":
      return cmdWait(positional, flags);
    case "ask":
      return cmdAsk(positional, flags);
    case "consult":
      return cmdConsult(positional, flags);
    case "council":
      return cmdCouncil(positional, flags);
    case "broadcast":
      return cmdBroadcast(positional, flags);
    case "reply":
      return cmdReply(positional);
    case "source":
      return cmdSource(positional, flags);
    case "trigger":
      return cmdTrigger(positional, flags);
    default:
      console.log(HELP);
  }
}

main().catch((err) => {
  console.error("Error: " + (err && err.message ? err.message : String(err)));
  process.exitCode = 1;
});
`;
